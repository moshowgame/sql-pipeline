    let current = localStorage.getItem('lang') || 'en';
    if (!DICT[current]) {
        current = 'en';
    }

    function t(key, params) {
        let text = (DICT[current] && DICT[current][key]) || (DICT.en[key] || key);
        if (params) {
            Object.keys(params).forEach(function (k) {
                text = text.split('{' + k + '}').join(params[k]);
            });
        }
        return text;
    }

    function applyI18n(root) {
        root = root || document;
        root.querySelectorAll('[data-i18n]').forEach(function (el) {
            el.textContent = t(el.getAttribute('data-i18n'));
        });
        root.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
            el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
        });
        root.querySelectorAll('[data-i18n-title]').forEach(function (el) {
            el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
        });
        document.documentElement.lang = current === 'zh' ? 'zh-CN' : 'en';
    }

    function injectSwitcher() {
        const flex = document.querySelector('.navbar .d-flex');
        if (!flex || document.getElementById('langSelect')) {
            return;
        }
        const wrap = document.createElement('div');
        wrap.className = 'd-flex align-items-center me-3';
        wrap.innerHTML =
            '<select id="langSelect" class="form-select form-select-sm" style="width:92px">' +
            '<option value="en">English</option><option value="zh">中文</option></select>';
        flex.prepend(wrap);
        const select = document.getElementById('langSelect');
        select.value = current;
        select.onchange = function () {
            const lang = select.value;
            localStorage.setItem('lang', lang);
            // 同步后端 locale（错误消息等走 LANG Cookie）
            document.cookie = 'LANG=' + lang + ';path=/;max-age=31536000';
            location.reload();
        };
    }

    document.addEventListener('DOMContentLoaded', function () {
        applyI18n();
        injectSwitcher();
    });

    return { t: t, applyI18n: applyI18n, lang: function () { return current; } };
